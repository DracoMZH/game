const Scenarios = (() => {
  let idx = 0, score = 0, box = null, onFinishCb = null;
  const MAX = SCENARIOS.length * 2;

  function renderCase() {
    const s = SCENARIOS[idx];
    box.innerHTML = `
      <p class="muted sc-intro">Ситуации без единственно верной кнопки — как в жизни. Выбирай и читай цену решения.</p>
      <div class="sc-progress">Развилка ${idx + 1} из ${SCENARIOS.length} · очки: ${score} / ${MAX}</div>
      <div class="sc-card">
        <span class="sc-kind">${s.kind}</span>
        <p class="sc-text">${s.situation}</p>
      </div>
      <div class="sc-choices"></div>
      <div class="sc-verdict"></div>`;
    const wrap = box.querySelector(".sc-choices");
    s.choices.forEach((c, i) => {
      const b = document.createElement("button");
      b.className = "sc-choice";
      b.textContent = c.txt;
      b.onclick = () => choose(i);
      wrap.appendChild(b);
    });
  }

  function choose(i) {
    const s = SCENARIOS[idx];
    const c = s.choices[i];
    score += c.score;
    c.v === "good" ? Sound.good() : c.v === "bad" ? Sound.bad() : Sound.click();
    const btns = [...box.querySelectorAll(".sc-choice")];
    btns.forEach((b, bi) => {
      b.disabled = true;
      b.classList.add("v-" + s.choices[bi].v);
    });
    btns[i].classList.add("picked");
    const label = c.v === "good" ? "Сильное решение" : c.v === "ok" ? "Приемлемо" : "Дорогая ошибка";
    const v = box.querySelector(".sc-verdict");
    v.innerHTML = `<div class="sc-tag ${c.v}">${label} · +${c.score}</div><div class="why">${c.why}</div>`;
    const next = document.createElement("button");
    next.className = "primary";
    next.textContent = idx + 1 < SCENARIOS.length ? "Следующая развилка →" : "Итог →";
    next.onclick = () => { idx++; idx < SCENARIOS.length ? renderCase() : finish(); };
    v.appendChild(next);
  }

  function finish() {
    const pct = score / MAX;
    const verdict = pct >= 0.9 ? "Хладнокровие и зрелость. Тебя сложно поймать на эмоциях и жадности."
      : pct >= 0.65 ? "Крепкое суждение, но есть куда расти — перечитай разборы дорогих ошибок."
      : "Эмоции и жадность пока ведут. Именно на этих развилках теряют реальные деньги — пройди ещё раз.";
    box.innerHTML = `
      <div class="result">
        <div>Очки суждения</div><div class="score">${score} / ${MAX}</div>
        <p>${verdict}</p>
        <p class="muted">Общий знаменатель верных решений: управляй риском, не верь «гарантиям», держи ключи у себя и не торгуй на эмоциях.</p>
      </div>`;
    if (pct >= 0.65) Sound.fanfare();
    if (onFinishCb) onFinishCb({ score, max: MAX });
  }

  return {
    open(container, onFinish) {
      onFinishCb = onFinish;
      idx = 0; score = 0; box = container;
      renderCase();
    },
    close() {},
  };
})();
